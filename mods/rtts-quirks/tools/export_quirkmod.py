r"""Write quirkmod.txt (read by the port module runtime/mlb/quirkmod.c) from quirks.json, the single source of rules.

Line format (# starts a comment):
  param <name> <number>
  quirk <bit> <both|hitter|pitcher> <family> <name...>
  carry <quirk bit> <carry bit>
  college <idx> <hitter family> <pitcher family> <prestige>
  draftchance <pick> <probability>
  host <scene id> <college|draft|spring>
  stat <name> <bat|pitch> <u8|i16|derived> <off>  last-season stat in the RTTS stats set (bat) or its pitcher block
  attr <name> <attribute id>                      hitter area ratings for the focus (contact / power / speed)
  force <name> <value...>                         test only: replaces a live input (velocity, movement, control, ...)

usage: python -E -s export_quirkmod.py [out path]   (default: ..\quirkmod.txt)
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from build_offers import MOMENT_OF_HOST  # noqa: E402

# Last-season stat locations. Field names and offsets from the game's own serializers (atlas fields.tsv:
# stat_batting_record_register_members = the 0x70-byte set, stat_register_pitching_stat_fields = its pitcher block at
# set+0x68). Checked in game 2026-11-17 against a box score: earned runs, home/away ER and innings (stored as OUTS),
# strikeouts, batters faced, walks, hits. Not yet seen non-zero in game: the batting fields, saves, quality starts
# (0x34 is an unnamed byte between complete games 0x32 and wins 0x35; static reading of f_70018392f0).
# 'derived' = computed by the module: hbp = PA - AB - BB - SF - SH (no named hit-by-pitch field in the batting record).
STATS = [('ab', 'bat', 'i16', 0x00), ('h', 'bat', 'i16', 0x0a), ('tb', 'bat', 'i16', 0x16), ('pa', 'bat', 'i16', 0x1a),
         ('bb', 'bat', 'u8', 0x4f), ('sf', 'bat', 'u8', 0x54), ('sh', 'bat', 'u8', 0x55), ('hbp', 'bat', 'derived', 0),
         ('home_ab', 'bat', 'i16', 0x06), ('away_ab', 'bat', 'i16', 0x08), ('risp_ab', 'bat', 'u8', 0x23),
         ('risp_h', 'bat', 'u8', 0x29), ('home_h', 'bat', 'u8', 0x2a), ('away_h', 'bat', 'u8', 0x2b),
         ('steals', 'bat', 'u8', 0x60),
         ('er', 'pitch', 'i16', 0x12), ('ip', 'pitch', 'i16', 0x26),
         ('home_er', 'pitch', 'i16', 0x14), ('away_er', 'pitch', 'i16', 0x16), ('home_ip', 'pitch', 'i16', 0x28),
         ('away_ip', 'pitch', 'i16', 0x2a), ('quality_starts', 'pitch', 'u8', 0x34), ('saves', 'pitch', 'u8', 0x41)]
# hitter ratings: attribute record (player_attr_serialize_visit_fields; f_700183bb94 ids < 0x18 read rec[id]):
# m_nContactLeft/Right 1/2, m_nPowerLeft/Right 3/4, m_nSpeed 0xc (left and right are averaged). Checked in game:
# rank 0 = card OVR, durability 0xb moved 43 -> 44 after a workout.
ATTRS = [('contact', 1, 2), ('power', 3, 4), ('speed', 0xc)]


def export(cfg):
    out = ['# generated by tools/export_quirkmod.py from quirks.json; edit quirks.json, then run the exporter']
    p = lambda k, v: out.append(f'param {k} {v}')   # noqa: E731
    p('max_owned', cfg['max_owned'])
    sz = cfg['offer_size']
    p('size_college_initial', sz['college']['initial']); p('size_college_full', sz['college']['full'])
    p('size_draft_first', sz['draft']['first_overall']); p('size_draft_round1', sz['draft']['round_1'])
    p('size_draft_later', sz['draft']['later']); p('size_max', sz['max'])
    lk = cfg['locks']
    p('lock_outlier1_min', lk['Outlier I']['min']); p('lock_outlier2_above', lk['Outlier II']['above'])
    p('lock_break_above', lk['Break Outlier']['best_movement_above'])
    e = cfg['earned']
    p('earn_outlier1_min', e['Outlier I']['min']); p('earn_outlier2_min', e['Outlier II']['min'])
    p('earn_break_min', e['Break Outlier']['best_movement_min'])
    p('earn_break_second_min', e['Break Outlier'].get('second_movement_min', 0))
    p('earn_risp_avg', e['Situational Hitter']['risp_avg_min']); p('earn_risp_ab', e['Situational Hitter']['risp_ab_min'])
    hb = e['Homebody']
    p('earn_side_avg', hb['hitter_avg_min']); p('earn_side_ab', hb['ab_min']); p('earn_side_era', hb['pitcher_era_max'])
    p('earn_side_ip_starter', hb['ip_min']['starter']); p('earn_side_ip_reliever', hb['ip_min']['reliever'])
    p('earn_side_ip_closer', hb['ip_min']['closer'])
    p('earn_saves', e['Stopper']['saves_min']); p('earn_qs', e['Stopper']['quality_starts_min'])
    p('earn_steals', e['Table Setter']['steals_min'])
    sb = cfg['spring_by_season']
    for i, t in enumerate(sb['hitter']['tiers']):
        p(f'spring_hit_tier{i}_min', t['min']); p(f'spring_hit_tier{i}_size', t['size'])
    for i, t in enumerate(sb['pitcher']['tiers']):
        p(f'spring_pit_tier{i}_max', t['max']); p(f'spring_pit_tier{i}_size', t['size'])
    p('spring_min_pa', sb['hitter']['min_pa']); p('spring_min_ip', sb['pitcher']['min_ip'])
    p('spring_short', sb['short_season'])
    p('twoway_warn_at', cfg['two_way']['warn_at']); p('twoway_warned_bit', cfg['two_way']['warned_bit'])
    p('college_prestige_min', cfg['lock_bypass']['college_prestige_min'])
    p('college_given_bit', 28)     # quirk-word spare bit: the college offer was already queued
    p('offer_details', 1)          # 1 = list each offered quirk's short text in the offer line
    p('message_lifetime', 250)     # inbox ticks before an unopened offer expires (the game's own max is 10)
    p('spring_in_college', 0)      # 1 = also queue spring offers in the college seasons after the first
    p('stats_slot', 1)             # career history slot: 0 = this season, 1 = last season (f_700044b460 shifts)
    p('ip_divisor', 3)             # innings are stored as outs
    for q in cfg['quirks']:
        out.append(f"quirk {q['bit']} {q['role']} {q['family']} {q['name']}")
    for q in cfg['quirks']:              # short text shown under the offer line, one per offered quirk
        out.append(f"qtext {q['bit']} {q['short']}")
    for n, b in cfg['carry_bits'].items():
        out.append(f"carry {next(q['bit'] for q in cfg['quirks'] if q['name'] == n)} {b}")
    for i, c in enumerate(cfg['colleges']):
        out.append(f"college {i} {c['hitter']} {c['pitcher']} {c['prestige']}")
    for pick, pr in cfg['lock_bypass']['draft_pick_chance'].items():
        out.append(f'draftchance {pick} {pr}')
    for sid, moment in MOMENT_OF_HOST.items():
        out.append(f'host {sid} {moment}')
    for name, blk, typ, off in STATS:
        out.append(f'stat {name} {blk} {typ} {off:#x}')
    for name, *ids in ATTRS:
        out.append(f'attr {name} ' + ' '.join(f'{i:#x}' for i in ids))
    for name, val in (cfg.get('debug', {}).get('force_inputs') or {}).items():
        vals = val if isinstance(val, list) else [val]
        out.append('force ' + name + ' ' + ' '.join(str(v) for v in vals))
    return '\n'.join(out) + '\n'


def main():
    cfg = json.loads((HERE.parent / 'quirks.json').read_text(encoding='utf-8'))
    dst = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / 'quirkmod.txt'
    dst.write_text(export(cfg), encoding='utf-8')
    print('wrote', dst, len(dst.read_text(encoding='utf-8').splitlines()), 'lines')


if __name__ == '__main__':
    main()
